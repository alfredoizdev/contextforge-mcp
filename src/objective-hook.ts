import { join } from "path";

/**
 * Claude Code `UserPromptSubmit` hook that records the user's prompts so
 * `contextforge-mcp recall` can restore the session objective after a
 * compaction (see recall.ts).
 *
 * Why a generated script instead of `npx -y contextforge-mcp …`: this hook
 * runs on EVERY prompt. `npx` costs 0.4–0.8 s per start; plain `node` on a
 * local file costs ~50 ms. The script is dependency-free CommonJS, written
 * by `init` into the project's `.claude/hooks/` and executed through
 * `$CLAUDE_PROJECT_DIR` (the path Claude Code documents for hook scripts;
 * it stays fixed inside git worktrees).
 */

export const OBJECTIVE_HOOK_RELATIVE_PATH = ".claude/hooks/contextforge-objective.cjs";

/** Exact hook command written by `init`. Keep in sync with README. */
export const OBJECTIVE_HOOK_COMMAND = 'node "$CLAUDE_PROJECT_DIR/.claude/hooks/contextforge-objective.cjs"';

/** Seconds; Claude Code's own default for UserPromptSubmit is 30 s. */
export const OBJECTIVE_HOOK_TIMEOUT_S = 5;

/** Where session prompt logs live. `CONTEXTFORGE_HOME` overrides the home dir (tests). */
export function sessionsDir(homeDir: string): string {
  return join(homeDir, ".contextforge", "sessions");
}

export const OBJECTIVE_HOOK_VERSION = 1;

/**
 * The script body. Hard rules, because its stdout would be injected into the
 * model's context and a non-zero exit would surface as an error to the user:
 * never write to stdout, never exit non-zero, bound every input.
 */
export const OBJECTIVE_HOOK_SCRIPT = `// contextforge-mcp objective hook v${OBJECTIVE_HOOK_VERSION} — generated by \`contextforge-mcp init\`.
// Safe to commit. Regenerate with \`npx contextforge-mcp init\`.
//
// Runs on Claude Code's UserPromptSubmit event and appends the prompt to
// ~/.contextforge/sessions/<session_id>.jsonl (local only, never uploaded) so
// that \`contextforge-mcp recall\` can put the session objective back into the
// context after a compaction. Prints nothing and always exits 0, so it can
// never block or slow a prompt. To disable, remove the UserPromptSubmit hook
// group from .claude/settings.json.
"use strict";
var MAX_PROMPT_CHARS = 600;
var MAX_FILE_BYTES = 64 * 1024;
var MAX_STDIN_CHARS = 1000000;

function record(raw) {
  try {
    var j = JSON.parse(raw);
    if (!j || typeof j.session_id !== "string" || typeof j.prompt !== "string") return;
    var sid = j.session_id.replace(/[^A-Za-z0-9_-]/g, "");
    if (!sid) return;
    var prompt = j.prompt.replace(/\\s+/g, " ").trim();
    if (!prompt || prompt.charAt(0) === "/") return;
    var fs = require("fs");
    var path = require("path");
    var os = require("os");
    var home = process.env.CONTEXTFORGE_HOME || os.homedir();
    var dir = path.join(home, ".contextforge", "sessions");
    fs.mkdirSync(dir, { recursive: true });
    var file = path.join(dir, sid + ".jsonl");
    try {
      if (fs.statSync(file).size >= MAX_FILE_BYTES) return;
    } catch (e) {}
    var entry = {
      t: Date.now(),
      turn: typeof j.turn === "number" ? j.turn : null,
      cwd: typeof j.cwd === "string" ? j.cwd : null,
      prompt: prompt.slice(0, MAX_PROMPT_CHARS),
    };
    fs.appendFileSync(file, JSON.stringify(entry) + "\\n", { mode: 0o600 });
  } catch (e) {}
}

if (process.stdin.isTTY) process.exit(0);
var buf = "";
process.stdin.setEncoding("utf8");
process.stdin.on("data", function (d) {
  if (buf.length < MAX_STDIN_CHARS) buf += d;
});
process.stdin.on("end", function () {
  record(buf);
  process.exit(0);
});
process.stdin.on("error", function () {
  process.exit(0);
});
setTimeout(function () {
  process.exit(0);
}, 3000).unref();
`;
